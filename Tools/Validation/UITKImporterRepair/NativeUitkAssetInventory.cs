using System;
using System.IO;
using System.Linq;
using Newtonsoft.Json;
using UnityEditor;
using UnityEngine;
public static class NativeUitkAssetInventory
{
 public static void Run()
 {
  if (!Application.dataPath.Contains("/.local/maze-native-probe/")) throw new InvalidOperationException("Owned clone required");
  const string targetGuid="f26621d71421141298a9a8cf0dc80574";
  const string mask="Assets/Art/ModernizationPlaceholders/Sprites/PLACEHOLDER_DiagonalWiper.png";
  if (!Directory.Exists("Assets/Art/ModernizationPlaceholders/Sprites")) Directory.CreateDirectory("Assets/Art/ModernizationPlaceholders/Sprites");
  if (!File.Exists(mask))
  {
   if (!string.IsNullOrEmpty(AssetDatabase.GUIDToAssetPath(targetGuid))) throw new InvalidOperationException("Original missing mask GUID now resolves");
   var texture=new Texture2D(64,64,TextureFormat.RGBA32,false);
   var pixels=new Color32[64*64];
   for(int y=0;y<64;y++) for(int x=0;x<64;x++) pixels[y*64+x]=new Color32(255,255,255,(byte)(x>=y?255:0));
   texture.SetPixels32(pixels);texture.Apply();File.WriteAllBytes(mask,texture.EncodeToPNG());UnityEngine.Object.DestroyImmediate(texture);
   AssetDatabase.ImportAsset(mask,ImportAssetOptions.ForceSynchronousImport);
   var importer=(TextureImporter)AssetImporter.GetAtPath(mask);importer.textureType=TextureImporterType.Sprite;importer.spriteImportMode=SpriteImportMode.Single;importer.mipmapEnabled=false;importer.alphaIsTransparency=true;importer.textureCompression=TextureImporterCompression.Uncompressed;importer.SaveAndReimport();
   var current=AssetDatabase.AssetPathToGUID(mask);var meta=File.ReadAllText(mask+".meta");if(!meta.Contains("guid: "+current))throw new InvalidOperationException("Native mask GUID guard");File.WriteAllText(mask+".meta",meta.Replace("guid: "+current,"guid: "+targetGuid));AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
  }
  var paths=new[]{mask,"Assets/AddressableResources/Collections/Flags/Flag_Demon/Icon_Flag_Demon.png","Assets/AddressableResources/Collections/CharacterSkins/PunkFemale/Icon_Char_PunkFemale.png","Assets/Art/UI/Sprites/Home/background-popup-generic.png","Assets/Art/UI/Sprites/Home/background-pending-party-invite.png","Assets/Art/UI/Templates/Resources/TemplateRewardDisplayContainer.uxml"};
  var assets=paths.SelectMany(path=>AssetDatabase.LoadAllAssetsAtPath(path).Select(asset=>{if(!AssetDatabase.TryGetGUIDAndLocalFileIdentifier(asset,out string guid,out long fileId))throw new InvalidOperationException("Native asset identity lookup failed: "+path);return new{path,guid,fileId,name=asset.name,type=asset.GetType().FullName};})).ToArray();
  if(paths.Any(path=>!assets.Any(asset=>asset.path==path)))throw new InvalidOperationException("Missing actual URI target");
  File.WriteAllText("uitk-repair-native-asset-inventory.json",JsonConvert.SerializeObject(assets,Formatting.Indented));Debug.Log("[UITK Asset Inventory] PASS: six native targets, diagonal placeholder generated by real Unity.");
 }
}
